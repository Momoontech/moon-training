const getContentPart = (core, partId) => {
    const part = getNode(core, partId);
    if (part.type !== NodeType.Part || part.partType.get() !== PartType.multiClosetSectionContent) {
        throw new Error(`Node with ID ${partId} is not a multi closet section content part.`);
    }
    return part;
};

export { getContentPart as default };
